// greet: 名前を受け取り、あいさつ文を組み立てて返す関数
function greet(name) {
  // なぜこう書くのか:
  // テンプレートリテラル（バッククォートで囲む書き方）を使うと、
  // 文字列の連結（+ でつなげる書き方）よりも読みやすく、
  // どこに変数の値が入るのかが一目で分かる。
  return `こんにちは、${name}さん！`;
}

// add: 2つの数値を受け取り、足し算した結果を返す関数
function add(a, b) {
  // なぜこう書くのか:
  // 単純な足し算だが、関数として名前をつけておくことで、
  // 「何をしている処理なのか」が呼び出し側からも分かりやすくなる。
  // また、将来この関数の中身だけを変更すれば、
  // 呼び出している全ての場所に影響を反映できる（部品化のメリット）。
  return a + b;
}

module.exports = { greet, add };
